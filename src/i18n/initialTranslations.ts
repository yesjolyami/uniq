export function getInitialTranslation(locale: keyof typeof initialTranslations, text: string) {
  const dictionary = initialTranslations[locale] as Record<string, string>;
  const exact = dictionary[text];
  if (exact) return exact;

  // The content API limits some legacy texts by length. Match that stable
  // Russian prefix to keep old saved content translated after normalization.
  if (text.length < 40) return undefined;
  const source = Object.keys(dictionary).find((key) => key.startsWith(text));
  return source ? dictionary[source] : undefined;
}
